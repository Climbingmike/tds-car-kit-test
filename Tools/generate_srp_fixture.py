#!/usr/bin/env python3
"""Independent Python hashlib/pow oracle for the native AirPlay SRP implementation."""
from pathlib import Path
import hashlib, re
root = Path(__file__).resolve().parents[1]
source = (root/'Sources/TDSCarKitCore/PairSetup.swift').read_text()
n = int(re.search(r'BigUInt\("([A-F0-9]+)"', source)[1], 16)
def raw(n): return n.to_bytes(max(1, (n.bit_length()+7)//8), 'big')
def pad(n): return n.to_bytes(384, 'big')
def h(*args): return hashlib.sha512(b''.join(args)).digest()
salt=bytes(range(16)); private=bytes(range(1,33)); a=int.from_bytes(bytes(range(33,65)),'big'); b=int.from_bytes(private,'big')
k=int.from_bytes(h(pad(n),pad(5)),'big'); x=int.from_bytes(h(salt,h(b'Pair-Setup:3939')),'big')
v=pow(5,x,n); A=pow(5,a,n); B=(k*v+pow(5,b,n))%n
u=int.from_bytes(h(pad(A),pad(B)),'big')
S=pow((B-k*pow(5,x,n))%n,a+u*x,n)
assert S==pow(A*pow(v,u,n)%n,b,n)
key=h(raw(S)); xor=bytes(x^y for x,y in zip(h(raw(n)),h(raw(5))))
proof=h(xor,h(b'Pair-Setup'),salt,pad(A),pad(B),key); server=h(pad(A),proof,key)
values=dict(salt=salt, privateBytes=private, peer=pad(A), publicKey=pad(B), key=key, proof=proof, serverProof=server)
text='// Generated by Tools/generate_srp_fixture.py using Python hashlib and integer pow.\nimport Foundation\nenum SRPFixture {\n'
for name,value in values.items(): text+=f'    static let {name} = "{value.hex()}"\n'
text+='}\n'
(root/'Tests/TDSCarKitCoreTests/SRPFixture.swift').write_text(text)
